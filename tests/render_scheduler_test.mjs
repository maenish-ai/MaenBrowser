import {strict as assert} from 'node:assert';
import {scheduleRender} from '../assets/companion/render-scheduler.js';
const events={},timers=new Map();let serial=0,renders=0,now=0,finish;
globalThis.document={hidden:true,addEventListener:(name,fn)=>events[name]=fn};
globalThis.window={addEventListener:(name,fn)=>events[name]=fn};
globalThis.performance={now:()=>now};
globalThis.setTimeout=(fn,delay)=>{timers.set(++serial,{fn,due:now+delay});return serial;};
globalThis.clearTimeout=id=>timers.delete(id);
const run=async()=>{const [id,t]=[...timers][0];timers.delete(id);now=t.due;await t.fn();};
let block=false;
const schedule=scheduleRender(async()=>{renders++;if(block)await new Promise(r=>finish=r);},e=>{throw e;},{minInterval:1000});
for(let i=0;i<100;i++)schedule();assert.equal(timers.size,0);
document.hidden=false;events.visibilitychange();await run();assert.equal(renders,1);
assert.equal(timers.size,0,'no idle polling');
for(let i=0;i<100;i++)schedule();
assert.equal(timers.size,1);assert.equal([...timers.values()][0].due,1150,'event storms limited to one second');
document.hidden=true;events.visibilitychange();assert.equal(timers.size,0,'hidden page cancels timer');
document.hidden=false;events.visibilitychange();await run();assert.equal(renders,2);
block=true;schedule();const pending=run();schedule();schedule();
assert.equal(timers.size,0,'no overlapping renders');
events.pagehide();finish();await pending;
assert.equal(timers.size,0,'in-flight render cannot restart hidden page');
events.pageshow();assert.equal(timers.size,1);block=false;await run();
assert.equal(renders,4);assert.equal(timers.size,0);
console.log('Refresh limits, hidden-page cancellation, event coalescing and in-flight lifecycle passed');
